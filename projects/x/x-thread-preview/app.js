function formatCount(text) {
  return `${[...text].length} 字`;
}

function showToast(message = "已复制") {
  toast.textContent = message;
  toast.classList.add("show");
  window.setTimeout(() => toast.classList.remove("show"), 1500);
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    showToast("已复制到剪贴板");
  } catch {
    const area = document.createElement("textarea");
    area.value = text;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.left = "-9999px";
    document.body.appendChild(area);
    area.select();
    document.execCommand("copy");
    area.remove();
    showToast("已复制到剪贴板");
  }
}

function escapeHtml(value) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function tweetTemplate(text, options = {}) {
  const label = options.label || "Thread 连续帖";
  const isThread = options.thread || false;
  const indexLabel = options.indexLabel || "";
  const countClass = [...text].length > 280 ? "char-count warn" : "char-count";

  return `
    <article class="tweet ${isThread ? "thread-item" : ""}">
      <div class="mini-avatar" aria-hidden="true"></div>
      <div>
        <div class="tweet-head">
          <span class="tweet-name">France | AI印钞机实验室</span>
          <span class="verified">✓</span>
          <span class="tweet-handle">@France441483</span>
          <span class="tweet-time">· 刚刚</span>
        </div>
        <div class="tweet-text">${escapeHtml(text)}</div>
        <div class="tweet-actions">
          <div class="action-stats">
            <span>💬 0</span>
            <span>↻ 0</span>
            <span>♡ 0</span>
            <span>▥ 预览</span>
          </div>
          <span class="${countClass}">${indexLabel}${formatCount(text)} · ${label}</span>
          <button class="copy-button" data-copy="${encodeURIComponent(text)}" type="button">复制</button>
        </div>
      </div>
    </article>
  `;
}

